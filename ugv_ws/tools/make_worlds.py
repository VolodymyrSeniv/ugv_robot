"""Write the two simulation worlds into src/ugv_description/worlds/.

test_world_aliased.sdf : one texture shared by all walls/obstacles (perceptual aliasing, hard case)
test_world.sdf         : a unique texture per wall/obstacle
__TEXDIR__ is replaced by sim.launch.py with the installed textures path.
"""
import sys

BOXES = [  # name, pose, size
    ('wall_n', '0 10 1 0 0 0', (20.6, 0.3, 2)), ('wall_s', '0 -10 1 0 0 0', (20.6, 0.3, 2)),
    ('wall_e', '10 0 1 0 0 0', (0.3, 20, 2)), ('wall_w', '-10 0 1 0 0 0', (0.3, 20, 2)),
    ('box1', '4 1.5 0.5 0 0 0.3', (1, 1, 1)), ('box2', '7 -2 0.75 0 0 0', (1.5, 0.5, 1.5)),
    ('box3', '2 -3 0.4 0 0 0.8', (0.8, 0.8, 0.8)), ('box4', '-3 3 0.6 0 0 0.5', (1.2, 1.2, 1.2)),
]


def model(name, pose, size, tex):
    sx, sy, sz = size
    return f'''    <model name="{name}"><static>true</static><pose>{pose}</pose>
      <link name="l">
        <collision name="c"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry></collision>
        <visual name="v"><geometry><box><size>{sx} {sy} {sz}</size></box></geometry>
          <material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse>
            <pbr><metal><albedo_map>__TEXDIR__/{tex}</albedo_map><metalness>0</metalness><roughness>1</roughness></metal></pbr></material></visual>
      </link></model>
'''


def world(unique):
    models = ''.join(model(n, p, s, f'{n}.png' if unique else 'wall.png') for n, p, s in BOXES)
    return f'''<?xml version="1.0"?>
<!-- Generated by tools/make_worlds.py. __TEXDIR__ is substituted by sim.launch.py. -->
<sdf version="1.8">
  <world name="test_world">
    <physics name="4ms" type="ignored"><max_step_size>0.004</max_step_size></physics>
    <plugin filename="ignition-gazebo-physics-system" name="ignition::gazebo::systems::Physics"/>
    <plugin filename="ignition-gazebo-user-commands-system" name="ignition::gazebo::systems::UserCommands"/>
    <plugin filename="ignition-gazebo-scene-broadcaster-system" name="ignition::gazebo::systems::SceneBroadcaster"/>
    <plugin filename="ignition-gazebo-sensors-system" name="ignition::gazebo::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <plugin filename="ignition-gazebo-imu-system" name="ignition::gazebo::systems::Imu"/>

    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows><pose>0 0 10 0 0 0</pose>
      <diffuse>1 1 1 1</diffuse><specular>0.1 0.1 0.1 1</specular>
      <direction>-0.3 0.2 -0.9</direction>
    </light>

    <model name="ground">
      <static>true</static>
      <link name="link">
        <collision name="c"><geometry><plane><normal>0 0 1</normal><size>22 22</size></plane></geometry></collision>
        <visual name="v"><geometry><plane><normal>0 0 1</normal><size>22 22</size></plane></geometry>
          <material><ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse>
            <pbr><metal><albedo_map>__TEXDIR__/ground.png</albedo_map><metalness>0</metalness><roughness>1</roughness></metal></pbr></material></visual>
      </link>
    </model>

{models}  </world>
</sdf>
'''


dst = sys.argv[1]
open(f'{dst}/test_world.sdf', 'w').write(world(True))
open(f'{dst}/test_world_aliased.sdf', 'w').write(world(False))
print('worlds written')
